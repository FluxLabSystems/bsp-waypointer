"""MC2 ADR-0232: CTF objectives on the waypoints, and team-only hazards.

A CTF map's spawn-room guard is a trigger_hurt filtered to one team. It must
restrict that team's waypoints (W_FL_NORED bars team 2, W_FL_NOBLU team 3, by
engine team number as RCBot3 reads them) instead of cutting the room out of the
graph for both teams. --ctf-layout flags the objectives a layout names.
"""

from bsp_waypointer.bsp_parser import Entity
from bsp_waypointer.constants import WaypointFlag
from bsp_waypointer.ctf_layout import apply_ctf_layout, parse_layout, resolve_layout_path
from bsp_waypointer.entity_analyzer import HL2DMEntityAnalyzer, HurtVolume
from bsp_waypointer.vector import Vector3
from bsp_waypointer.waypoint_converter import HL2DMWaypointConverter, Waypoint

LAYOUT = """// Generated by tools/build/gen_ctf_layouts.py
"CTFLayout"
{
	"version"	"1"
	"family"	"physflag"
	"submode"	"flag"
	"Base"
	{
		"team"	"2"
		"flag"	"0 0 0"
		"zonemins"	"-40 900 0"
		"zonemaxs"	"40 980 120"
	}
	"Base"
	{
		"team"	"3"
		"flag"	"2000 0 0"
	}
	"neutral"	"1000 0 0"
	"point"	"500 0 0"
	"point"	"1500 0 0"
	"Goal" { "team" "3" "mins" "990 990 0" "maxs" "1010 1010 50" }
	"Suppress" { "name" "rflag_shell" }
}
"""


def _wp(i, x, y, z=0.0, flags=WaypointFlag.W_FL_NONE):
    return Waypoint(index=i, origin=Vector3(x, y, z), flags=flags)


def test_parse_layout():
    lay = parse_layout(LAYOUT)
    assert lay.stands[2] == Vector3(0, 0, 0)
    assert lay.stands[3] == Vector3(2000, 0, 0)
    assert 2 in lay.zones and 3 not in lay.zones
    assert lay.goals[3][0] == Vector3(990, 990, 0)
    assert lay.neutral == Vector3(1000, 0, 0)
    assert lay.points == [Vector3(500, 0, 0), Vector3(1500, 0, 0)]


def test_apply_flags_the_nearest_live_waypoints():
    wps = [
        _wp(0, 10, 0),                                   # Combine stand
        _wp(1, 1990, 0),                                 # Rebels stand
        _wp(2, 1000, 5),                                 # neutral
        _wp(3, 0, 940, 0),                               # Combine zone centre
        _wp(4, 505, 0),                                  # point A
        _wp(5, 1500, 0, flags=WaypointFlag.W_FL_UNREACHABLE),  # point B, flagged: never used
        _wp(6, 1520, 0),                                 # point B's live neighbour
        _wp(7, 100, 0),                                  # near the Combine stand: defend
        _wp(8, 1000, 1000),                              # the Rebels' goal
        _wp(9, 5000, 5000),                              # far from everything
    ]
    counts = apply_ctf_layout(wps, parse_layout(LAYOUT))
    assert wps[0].has_flag(WaypointFlag.W_FL_FLAG)
    assert wps[1].has_flag(WaypointFlag.W_FL_FLAG)
    assert wps[2].has_flag(WaypointFlag.W_FL_FLAG)
    assert wps[3].has_flag(WaypointFlag.W_FL_CAPPOINT)
    assert wps[8].has_flag(WaypointFlag.W_FL_CAPPOINT)
    assert wps[4].has_flag(WaypointFlag.W_FL_CAPPOINT) and wps[4].area == 1
    assert not wps[5].has_flag(WaypointFlag.W_FL_CAPPOINT) and wps[5].area == 0
    assert wps[6].has_flag(WaypointFlag.W_FL_CAPPOINT) and wps[6].area == 2
    assert wps[7].has_flag(WaypointFlag.W_FL_DEFEND)
    assert not wps[9].flags
    assert counts["flag"] == 3 and counts["cappoint"] == 4 and counts["unplaced"] == 0


def test_an_objective_with_no_waypoint_near_is_reported_not_pinned():
    counts = apply_ctf_layout([_wp(0, 9000, 9000)], parse_layout(LAYOUT))
    assert counts["flag"] == 0 and counts["unplaced"] > 0


def test_resolve_layout_path(tmp_path):
    (tmp_path / "ctf_x.ctf.txt").write_text(LAYOUT)
    assert resolve_layout_path(tmp_path, "ctf_x") == tmp_path / "ctf_x.ctf.txt"
    assert resolve_layout_path(tmp_path, "ctf_y") is None
    assert resolve_layout_path(tmp_path / "ctf_x.ctf.txt", "anything") == tmp_path / "ctf_x.ctf.txt"


class _Bsp:
    def __init__(self, entities):
        self.entities = entities


def _filter(name, team, negated="0"):
    return Entity("filter_activator_team", {"classname": "filter_activator_team", "targetname": name,
                                            "filterteam": str(team), "negated": negated})


def test_filter_team_reads_the_filter_and_its_negation():
    a = HL2DMEntityAnalyzer()
    a._bsp = _Bsp([_filter("red_guard", 3), _filter("not_blue", 2, "1"), _filter("text_form", 2,
                   "Allow entities that match criteria")])
    assert a._filter_team("red_guard") == 3
    assert a._filter_team("RED_GUARD") == 3, "targetnames compare without case"
    assert a._filter_team("not_blue") == 3, "a negated filter passes the other team"
    assert a._filter_team("text_form") == 2, "Hammer's text form of 'not negated'"
    assert a._filter_team("missing") == 0
    assert a._filter_team("") == 0


def test_team_hazards_bar_only_their_team():
    conv = HL2DMWaypointConverter()
    conv._waypoints = [_wp(0, 0, 0, 10), _wp(1, 500, 0, 10), _wp(2, 1000, 0, 10)]
    conv._team_hazards = [
        HurtVolume(origin=Vector3(0, 0, 0), mins=Vector3(-50, -50, 0), maxs=Vector3(50, 50, 100), damage=20, team=3),
        HurtVolume(origin=Vector3(0, 0, 0), mins=Vector3(950, -50, 0), maxs=Vector3(1050, 50, 100), damage=20, team=2),
    ]
    conv._flag_team_hazards()
    assert conv._waypoints[0].has_flag(WaypointFlag.W_FL_NOBLU), "hurts team 3: NOBLU"
    assert not conv._waypoints[0].has_flag(WaypointFlag.W_FL_NORED)
    assert not conv._waypoints[1].flags, "outside both"
    assert conv._waypoints[2].has_flag(WaypointFlag.W_FL_NORED), "hurts team 2: NORED"
    assert conv.team_hazard_waypoints == 2
