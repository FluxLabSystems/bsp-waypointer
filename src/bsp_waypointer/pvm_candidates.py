@dataclass
class PvMParams:
    max_npc: int = 144
    max_large: int = 32
    spacing_small: float = 160.0
    spacing_large: float = 384.0
    open_radius: float = 192.0
    lift: float = 12.0
    hull_human: Tuple[float, float, float] = (26.0, 26.0, 72.0)
    hull_large: Tuple[float, float, float] = (80.0, 80.0, 100.0)


def hull_box(dims: Sequence[float]) -> Tuple[Point, Point]:
    w, d, h = float(dims[0]), float(dims[1]), float(dims[2])
    return (-w / 2.0, -d / 2.0, 0.0), (w / 2.0, d / 2.0, h)


def _clamp01(x: float) -> float:
    return 0.0 if x < 0.0 else 1.0 if x > 1.0 else x


@dataclass
class _Node:
    index: int
    origin: Point
    spawn_path: float          # path from the nearest player spawn (inf: none reaches)
    openness: float            # 0..1, neighbours within open_radius vs the pool's best
    tele: Optional[float]      # straight distance to the nearest teleporter exit
    pre: float = 0.0           # graph-only pre-score used by the selection


def candidate_pool(ctx: AnalysisContext, params: PvMParams) -> List[_Node]:
    """Eligible main waypoints with their graph-only measures, ascending by index."""
    g = ctx.graph
    spawn_pts = [s.origin for s in ctx.spawns]
    spawn_nodes = ctx.spawn_nodes()
    spawn_dist = ctx.dist_from(spawn_nodes) if spawn_nodes else [INF] * g.n
    eligible: List[int] = []
    for i in ctx.main_list:
        o = g.origins[i]
        if g.flags[i] & (EXCLUDE | TEAM_BARRED):
            continue
        if ctx.in_hazard(o):
            continue
        ns = nearest_straight(o, spawn_pts)
        if ns is not None and ns < SPAWN_EXCLUSION:
            continue
        nt = nearest_straight(o, ctx.teleport_exits)
        if nt is not None and nt < TELEPORT_EXCLUSION:
            continue
        eligible.append(i)
    index = SpatialIndex(g.origins, eligible, cell=params.open_radius)
    counts = {i: len(index.within(g.origins[i], params.open_radius)) for i in eligible}
    top = max(counts.values()) if counts else 1
    pool: List[_Node] = []
    for i in eligible:
        o = g.origins[i]
        node = _Node(i, o, spawn_dist[i], counts[i] / top if top else 0.0,
                     nearest_straight(o, ctx.teleport_exits))
        s_spawn = _spawn_score(node.spawn_path, bool(spawn_nodes))
        node.pre = 0.6 * s_spawn + 0.4 * node.openness
        pool.append(node)
    return pool


def _spawn_score(path: float, have_spawns: bool) -> float:
    if not have_spawns:
        return 1.0
    if path == INF:
        return 0.0
    return _clamp01((path - SPAWN_NEAR_PATH) / (SPAWN_FAR_PATH - SPAWN_NEAR_PATH))


def _tele_score(d: Optional[float]) -> float:
    if d is None:
        return 1.0
    return _clamp01((d - TELEPORT_EXCLUSION) / (512.0 - TELEPORT_EXCLUSION))


def _evaluate(ctx: AnalysisContext, node: _Node, hull: Tuple[Point, Point],
              min_headroom: float, lift: float) -> Optional[Dict[str, Any]]:
    """Trace-test and score one node. None when the hull does not fit."""
    probe = ctx.probe
    o = node.origin
    lifted = (o[0], o[1], o[2] + lift)
    have_spawns = bool(ctx.spawn_nodes())
    s_spawn = _spawn_score(node.spawn_path, have_spawns)
    s_tele = _tele_score(node.tele)
    near_hazard = ctx.in_hazard(o, HAZARD_NEAR)
    reasons: List[str] = []
    headroom: Optional[float] = None
    clearance: Optional[float] = None
    visible = False
    if probe is not None:
        if not probe.hull_fits(lifted, hull[0], hull[1]):
            return None
        headroom = probe.headroom(o, HEADROOM_PROBE)
        if headroom < min_headroom:
            return None
        rays = ctx.rays.get(node.index)
        if rays is None:
            rays = probe.clearances8(o, 512.0)
        clearance = sorted(rays)[len(rays) // 2]
        for s in ctx.spawns:
            if distance(s.origin, o) <= SIGHT_RANGE and probe.visible(s.origin, o):
                visible = True
                break
        s_clear = _clamp01(clearance / 256.0)
        s_head = _clamp01((headroom - min_headroom) / 64.0)
        score = (0.35 * s_spawn + 0.20 * s_clear + 0.15 * s_head
                 + 0.15 * (0.0 if visible else 1.0) + 0.15 * s_tele)
        if visible:
            reasons.append("spawn_visible")
        if clearance < 96.0:
            reasons.append("tight")
        if headroom < min_headroom + 32.0:
            reasons.append("low_headroom")
    else:
        score = 0.45 * s_spawn + 0.35 * node.openness + 0.20 * s_tele
        reasons.append("no_ray_tracing")
    if near_hazard:
        score *= 0.5
        reasons.append("near_hazard")
    if not have_spawns:
        reasons.append("no_player_spawns")
    elif node.spawn_path == INF:
        reasons.append("unreached_by_spawns")
    elif node.spawn_path < 768.0:
        reasons.append("near_player_spawn")
    if node.tele is not None and node.tele < 384.0:
        reasons.append("near_teleporter_exit")
    if ctx.degree(node.index) == 1:
        reasons.append("dead_end")
    if node.openness >= 0.75:
        reasons.append("open")
    return {
        "origin": pt(lifted),
        "score": rnd(score, 4),
        "headroom": rnd(headroom, 1),
        "clearance": rnd(clearance, 1),
        "nearest_player_spawn": rnd(node.spawn_path, 1),
        "nearest_teleporter": rnd(node.tele, 1),
        "in_hazard": near_hazard,
        "reasons": reasons,
        "waypoint": node.index,
    }


def _select_npc(ctx: AnalysisContext, pool: List[_Node], params: PvMParams) -> List[Dict[str, Any]]:
    """Score-weighted farthest-point sampling with per-pick hull validation."""
    if not pool:
        return []
    hull = hull_box(params.hull_human)
    min_head = float(params.hull_human[2])
    best = [INF] * len(pool)
    alive = [True] * len(pool)
    chosen: List[Dict[str, Any]] = []
    min2 = params.spacing_small * params.spacing_small
    first = True
    while len(chosen) < params.max_npc:
        pick = -1
        pick_val = -1.0
        for j, node in enumerate(pool):
            if not alive[j]:
                continue
            if first:
                val = node.pre
            else:
                if best[j] < min2:
                    continue
                val = math.sqrt(best[j]) * (0.5 + 0.5 * node.pre)
            if val > pick_val:
                pick, pick_val = j, val
        if pick < 0:
            break
        alive[pick] = False
        item = _evaluate(ctx, pool[pick], hull, min_head, params.lift)
        if item is None:
            continue  # refused: no distance update, the next best is tried
        first = False
        chosen.append(item)
        po = pool[pick].origin
        for j, node in enumerate(pool):
            d = dist2(node.origin, po)
            if d < best[j]:
                best[j] = d
    return chosen


def _select_large(ctx: AnalysisContext, pool: List[_Node], params: PvMParams) -> List[Dict[str, Any]]:
    """The most open waypoints, spacing_large apart, that fit the large hull."""
    hull = hull_box(params.hull_large)
    min_head = float(params.hull_large[2])
    order = sorted(pool, key=lambda n: (-n.openness, -n.pre, n.index))
    chosen: List[Dict[str, Any]] = []
    placed: List[Point] = []
    s2 = params.spacing_large * params.spacing_large
    for node in order:
        if len(chosen) >= params.max_large:
            break
        if any(dist2(node.origin, c) < s2 for c in placed):
            continue
        item = _evaluate(ctx, node, hull, min_head, params.lift)
        if item is None:
            continue
        chosen.append(item)
        placed.append(node.origin)
    return chosen


def teleport_blockers(ctx: AnalysisContext) -> List[Dict[str, Any]]:
    """TeleportBlocker suggestions: teleporter exits, and unreachable clusters.

    The Teleport module refuses a destination a blocker can see within its
    radius; a radius is always given (a bare triple means 1600 to the game).
    """
    out: List[Dict[str, Any]] = []
    for p in ctx.teleport_exits:
        out.append({"origin": pt(p), "radius": TELEPORT_BLOCKER_RADIUS, "reason": "teleporter_exit"})
    cls = ctx.comp.classification
    stuck = cls.sinks | cls.islands
    if stuck:
        g = ctx.graph
        und = g.undirected(stuck)
        groups = [grp for grp in connected_groups(und, stuck) if len(grp) >= UNREACHABLE_AREA_MIN]
        groups.sort(key=lambda grp: (-len(grp), grp[0]))
        for grp in groups:
            pts = [g.origins[i] for i in grp]
            c = (sum(p[0] for p in pts) / len(pts), sum(p[1] for p in pts) / len(pts),
                 sum(p[2] for p in pts) / len(pts))
            radius = max(distance(c, p) for p in pts) + 64.0
            out.append({"origin": pt(c), "radius": rnd(radius, 1), "reason": "unreachable_area"})
    return out[:TELEPORT_BLOCKERS_MAX]


def pvm_candidates(ctx: AnalysisContext, params: Optional[PvMParams] = None) -> Dict[str, Any]:
    """The ``candidates.pvm`` block of the analysis JSON."""
    params = params or PvMParams()
    pool = candidate_pool(ctx, params)
    npc = _select_npc(ctx, pool, params)
    large = _select_large(ctx, pool, params)
    return {
        "npc": npc,
        "large_npc": large,
        "teleport_blockers": teleport_blockers(ctx),
        "pool_size": len(pool),
    }
