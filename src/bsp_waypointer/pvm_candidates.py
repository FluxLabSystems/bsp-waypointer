"""
PvM monster spawn candidates (spec §19), and MC2's spawn node files.

MC2's PvM director places monsters only at a map's spawn nodes,
``maps/graphs/<map>.txt`` (``"MapData" { "NpcSpawns" {...} "LargeNpcSpawns"
{...} "TeleportBlockers" {...} }``). MC2's ``tools/build/gen_map_spawns.py``
derives them from the waypoints by farthest-point sampling alone. This module
proposes them with reasons:

- the pool is the main component's waypoints that need no jump, crouch,
  ladder, lift or fall (``gen_map_spawns``'s exclusion mask), are not inside a
  lethal hurt volume or a one-team spawn guard, and keep clear of the player
  spawns (``SPAWN_EXCLUSION``) and teleporter exits (``TELEPORT_EXCLUSION``);
- ``npc`` nodes are picked by farthest-point sampling weighted by a pre-score
  (path distance from the player spawns, open ground), at least
  ``spacing_small`` apart, and each pick must fit the human hull
  (HULL_HUMAN, 26x26x72) ``lift`` units above the floor;
- ``large_npc`` nodes are the most open waypoints, ``spacing_large`` apart,
  that fit HULL_LARGE (80x80x100);
- every node is scored 0..1 on spawn distance, clearance, headroom, being out
  of the spawns' sight and away from teleporter exits, and carries reasons.

The game still surveys every node at level load and validates each spawn at
runtime (occupancy, visibility, entities); these candidates are advisory.
``farthest_points`` and ``open_points`` are verbatim ports of
``gen_map_spawns.py`` (a parity test pins them).
"""

from __future__ import annotations

import math
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence, Tuple

from .analysis_graph import INF, SpatialIndex, connected_groups, distance
from .constants import WaypointFlag
from .tactical_metrics import AnalysisContext, nearest_straight, pt, rnd

Point = Tuple[float, float, float]

W_FL_JUMP = int(WaypointFlag.W_FL_JUMP)
W_FL_CROUCH = int(WaypointFlag.W_FL_CROUCH)
W_FL_UNREACHABLE = int(WaypointFlag.W_FL_UNREACHABLE)
W_FL_LADDER = int(WaypointFlag.W_FL_LADDER)
W_FL_LIFT = int(WaypointFlag.W_FL_LIFT)
W_FL_FALL = int(WaypointFlag.W_FL_FALL)
# gen_map_spawns.py's EXCLUDE, exactly
EXCLUDE = W_FL_JUMP | W_FL_CROUCH | W_FL_UNREACHABLE | W_FL_LADDER | W_FL_LIFT | W_FL_FALL
TEAM_BARRED = int(WaypointFlag.W_FL_NORED) | int(WaypointFlag.W_FL_NOBLU)

SPAWN_EXCLUSION = 192.0       # straight-line keep-out around a player spawn
TELEPORT_EXCLUSION = 128.0    # ... around a teleporter exit
HAZARD_NEAR = 64.0            # in_hazard: this close to a lethal hurt volume
SPAWN_NEAR_PATH = 384.0       # spawn-distance score is 0 at this path length ...
SPAWN_FAR_PATH = 1536.0       # ... and 1 at this one
SIGHT_RANGE = 1536.0          # spawns farther than this are not tested for sight
HEADROOM_PROBE = 256.0
TELEPORT_BLOCKER_RADIUS = 128.0
UNREACHABLE_AREA_MIN = 3      # an unreachable cluster this big gets a TeleportBlocker
TELEPORT_BLOCKERS_MAX = 64


# ---------------------------------------------------------------------------
# gen_map_spawns.py ports (keep verbatim: tests/test_pvm_candidates.py pins parity)
# ---------------------------------------------------------------------------


def dist2(a, b):
    return (a[0] - b[0]) ** 2 + (a[1] - b[1]) ** 2 + (a[2] - b[2]) ** 2


def farthest_points(points, k, min_spacing):
    if not points:
        return []
    # Start from the point nearest the centroid, so the pick is deterministic.
    cx = sum(p[0] for p in points) / len(points)
    cy = sum(p[1] for p in points) / len(points)
    first = min(points, key=lambda p: (p[0] - cx) ** 2 + (p[1] - cy) ** 2)
    chosen = [first]
    best = [dist2(p, first) for p in points]
    min2 = min_spacing * min_spacing
    while len(chosen) < k:
        i = max(range(len(points)), key=lambda j: best[j])
        if best[i] < min2:
            break
        chosen.append(points[i])
        for j, p in enumerate(points):
            d = dist2(p, points[i])
            if d < best[j]:
                best[j] = d
    return chosen


def open_points(points, k, radius, spacing):
    r2 = radius * radius
    scored = []
    for p in points:
        n = sum(1 for q in points if dist2(p, q) <= r2)
        scored.append((n, p))
    scored.sort(key=lambda t: (-t[0], t[1]))
    chosen = []
    s2 = spacing * spacing
    for _, p in scored:
        if all(dist2(p, c) >= s2 for c in chosen):
            chosen.append(p)
            if len(chosen) >= k:
                break
    return chosen


# ---------------------------------------------------------------------------
# MC2 spawn node files (maps/graphs/<map>.txt)
# ---------------------------------------------------------------------------

_TOKEN_RE = re.compile(r'"([^"]*)"|([{}])|(//[^\n]*)|([^\s"{}]+)')
GENERATED_HEADER = "// Generated by tools/build/gen_map_spawns.py"


@dataclass
class PvMNodeFile:
    """The node sections of a ``maps/graphs/<map>.txt`` MapData file, in file order."""

    npc: List[Point] = field(default_factory=list)
    large_npc: List[Point] = field(default_factory=list)
    teleport_blockers: List[Tuple[Point, Optional[float]]] = field(default_factory=list)
    generated: bool = False   # starts with gen_map_spawns.py's header
    path: Optional[str] = None


def _node(text: str) -> Optional[Tuple[Point, Optional[float]]]:
    parts = text.split()
    if len(parts) not in (3, 4):
        return None
    try:
        vals = [float(p) for p in parts]
    except ValueError:
        return None
    if not all(math.isfinite(v) for v in vals):
        return None
    return (vals[0], vals[1], vals[2]), (vals[3] if len(vals) == 4 else None)


def parse_pvm_nodes(text: str) -> PvMNodeFile:
    """Parse MapData text. Unknown sections are skipped; a malformed node is skipped."""
    out = PvMNodeFile(generated=text.lstrip("﻿").startswith(GENERATED_HEADER))
    tokens: List[str] = []
    for m in _TOKEN_RE.finditer(text):
        if m.group(3):
            continue
        tokens.append(m.group(1) if m.group(1) is not None else (m.group(2) or m.group(4)))
    depth = 0
    section: Optional[str] = None
    i = 0
    while i < len(tokens):
        tok = tokens[i]
        if tok == "{":
            depth += 1
            i += 1
            continue
        if tok == "}":
            depth -= 1
            if depth <= 1:
                section = None
            i += 1
            continue
        nxt = tokens[i + 1] if i + 1 < len(tokens) else None
        if nxt == "{":
            if depth == 1:
                section = tok.lower()
            i += 1
            continue
        if nxt is None:
            break
        if depth == 2 and section is not None:
            node = _node(tok)
            if node is not None:
                if section == "npcspawns":
                    out.npc.append(node[0])
                elif section == "largenpcspawns":
                    out.large_npc.append(node[0])
                elif section == "teleportblockers":
                    out.teleport_blockers.append(node)
        i += 2
    return out


def load_pvm_nodes(path: Path) -> PvMNodeFile:
    data = Path(path).read_bytes()
    if data[:2] in (b"\xff\xfe", b"\xfe\xff"):
        raise ValueError(f"{path}: UTF-16 text (the game refuses it too)")
    nodes = parse_pvm_nodes(data.decode("utf-8", errors="replace"))
    nodes.path = Path(path).name
    return nodes


def resolve_pvm_nodes_path(option: Path, map_name: str) -> Optional[Path]:
    """``--pvm-nodes`` names a file, or a ``maps/graphs`` directory holding ``<map>.txt``."""
    option = Path(option)
    if option.is_dir():
        candidate = option / (map_name + ".txt")
        return candidate if candidate.exists() else None
    return option if option.exists() else None


